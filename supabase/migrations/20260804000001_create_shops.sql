-- 나눔가게 테이블: 공개 읽기 / 로그인(관리자) 쓰기
create extension if not exists pgcrypto;

create table if not exists public.shops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default '식품',
  address text not null default '',
  service text not null default '',
  note text not null default '',
  frequency text not null default '',
  dong text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists shops_sort_order_idx on public.shops (sort_order, created_at);

-- updated_at 자동 갱신
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists shops_set_updated_at on public.shops;
create trigger shops_set_updated_at
  before update on public.shops
  for each row execute function public.set_updated_at();

-- 행 수준 보안
alter table public.shops enable row level security;

-- 공개: 누구나 읽기 (주민 공유용)
drop policy if exists "shops_public_read" on public.shops;
create policy "shops_public_read"
  on public.shops for select
  using (true);

-- 관리자(로그인 사용자)만 쓰기
