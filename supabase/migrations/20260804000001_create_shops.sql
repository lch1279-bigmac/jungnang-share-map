-- 나눔가게 테이블: 공개 읽기 / 로그인(관리자) 쓰기
create extension if not exists pgcrypto;

create table if not exists public.shops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default '식품',
  address text not null default '',
  intro text not null default '',
  note text not null default '',
  dong text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 이전 버전(service/frequency)로 이미 만들었던 경우를 대비한 보정
alter table public.shops add column if not exists intro text not null default '';
alter table public.shops drop column if exists service;
alter table public.shops drop column if exists frequency;

create index if not exists shops_sort_order_idx on public.shops (sort_order, created_at);

-- updated_at 자동 갱신
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists shops_set_updated_at on public.shops;
create trigger shops_set_updated_at
  before update on public.shops
  for each row execute function public.set_updated_at();

-- 행 수준 보안
alter table public.shops enable row level security;

-- 공개: 누구나 읽기 (주민 공유용)
drop policy if exists "shops_public_read" on public.shops;
create policy "shops_public_read"
  on public.shops for select
  using (true);

-- 관리자(로그인 사용자)만 쓰기
drop policy if exists "shops_auth_insert" on public.shops;
create policy "shops_auth_insert"
  on public.shops for insert to authenticated
  with check (true);

drop policy if exists "shops_auth_update" on public.shops;
create policy "shops_auth_update"
  on public.shops for update to authenticated
  using (true) with check (true);

drop policy if exists "shops_auth_delete" on public.shops;
create policy "shops_auth_delete"
  on public.shops for delete to authenticated
  using (true);

